    <h3>Client Brief</h3>
    <p>We worked with Bassett to translate their premium in-store design experience to the ecommerce site. We enabled users to select from the same set of options as if they were working with a designer 1-on-1, offering the same broad selection of fabrics and other furniture options.</p>
    <p>A particularly unique problem was dealing with the fact that different products and product options might have a wide range of colors available. Some might have only a handful while others might have 10s of options.</p>
    <p>Each product might also have an entirely different mix of options and option types than other poducts, so creating a system that was consistent yet also flexible would be a priority.</p>
    <ul>
      <li><span>Project Goals</span></li>
      <li>Include All Design Options</li>
      <li>Easy to Use</li>
      <li>Increase Conversion</li>
    </ul>
    <hr>
