    <h3>Final Wireframe</h3>
    <p>In the end we went with the option to embed all of the configuration options within the PDP itself. We iterated through the details of how to present the options to a user so they’re easy to use, driving confidence in their final selection and to purchase. Bassett has found this solution to be a very successful one in bringing their design choices to the ecommerce site to rival the in-store experience.</p>
