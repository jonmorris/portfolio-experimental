    <h2 class="right">Considering a Stand-Alone Experience</h2>
    <div>
      <p>We considered housing these customization options in a stand-alone experience separate from the PDP. This option allows much more flexibility for us to structure and present options that might need more space to give users all the information they need to make a decision. But, this option also takes users away from the product PDP with the rest of the product details they might want to have at hand. The other issue with this option is that for products that don’t have a lot of options this experience will feel very empty. Either that or some products will get the stand-alone experience and others won't, which might confuse users as to why they can’t find the button to configure on every product.</p>
    </div>
    <ul>
      <li><h2>Benefit</h2></li>
      <li>Allows for more flexiblity</li>
      <li><h2 class="second">Tradeoff</h2></li>
      <li>Doesn't work for simpler products</li>
    </ul>
